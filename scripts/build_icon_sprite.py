#!/usr/bin/env python3
"""Build backend/static/icons.svg from the Lucide static SVG set.

Sprint 28 (ADR-053): the shell and dashboard reference icons through
one self-hosted SVG sprite — ``<svg class="icon"><use
href="{% static 'icons.svg' %}#i-<name>"/></svg>`` — instead of
hand-drawn inline paths. The sprite is generated from the official
Lucide release (lucide-icons/lucide, ISC) so it can be regenerated or
extended deterministically:

    python3 scripts/build_icon_sprite.py /path/to/lucide/icons

The argument is the ``icons/`` directory of the lucide-icons release
zip (https://github.com/lucide-icons/lucide/releases). Each chosen
icon's inner shapes become one ``<symbol id="i-<name>">`` carrying
Lucide's native presentation (stroke 2, round caps/joins,
currentColor) so per-instance CSS only sets size and color.
"""

import re
import sys
from pathlib import Path

# Icon name -> where it is used (kept in sync with the templates).
ICONS = [
    # App shell / brand (base.html, registration/*)
    "book",  # brand mark
    "layout-dashboard",  # داشبورد
    "list",  # حساب‌ها
    "book-open",  # دفتر روزنامه
    "milestone",  # تراز افتتاحیه
    "package",  # محصولات
    "layers",  # موجودی انبار
    "repeat",  # حرکات انبار
    "clipboard-list",  # انبارگردانی‌ها
    "file-text",  # اسناد انبار
    "users",  # طرف‌حساب‌ها
    "shopping-cart",  # فاکتورهای خرید
    "credit-card",  # بدهی به تأمین‌کنندگان
    "receipt-text",  # فاکتورهای فروش
    "hand-coins",  # مطالبات از مشتریان
    "scroll-text",  # صورت‌حساب مشتری
    "wallet",  # حساب‌های خزانه
    "refresh-cw",  # دریافت و پرداخت
    "banknote",  # چک‌ها
    "clock",  # اقلام باز
    "landmark",  # تطبیق بانکی
    "notebook-pen",  # دفترچه‌های چک
    "chart-column",  # تراز آزمایشی
    "trending-up",  # صورت سود و زیان
    "scale",  # ترازنامه
    "building",  # شرکت‌ها
    "calendar",  # سال‌های مالی
    "log-out",  # خروج
    # Dashboard tiles, quick actions, empty states
    "coins",  # سود خالص دوره tile
    "arrow-down-left",  # اقلام باز — دریافتنی tile
    "arrow-up-right",  # اقلام باز — پرداختنی tile
    "triangle-alert",  # کالاهای کم‌موجودی tile
    "gauge",  # عملکرد panel
    "inbox",  # empty states
    "file-plus",  # quick action: سند جدید
    "plus",  # quick actions
]

ATTRS = (
    'fill="none" stroke="currentColor" stroke-width="2" '
    'stroke-linecap="round" stroke-linejoin="round"'
)


def inner_shapes(svg_text: str) -> str:
    """Strip the outer <svg ...> wrapper of a Lucide icon file."""
    body = re.sub(r"^\s*<svg\b[^>]*>", "", svg_text, count=1)
    body = re.sub(r"</svg>\s*$", "", body)
    lines = [ln.strip() for ln in body.strip().splitlines() if ln.strip()]
    return "\n    ".join(lines)


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    icons_dir = Path(sys.argv[1])
    out = Path(__file__).resolve().parent.parent / "backend" / "static" / "icons.svg"
    symbols = []
    for name in ICONS:
        src = icons_dir / f"{name}.svg"
        if not src.exists():
            print(f"missing icon in source set: {name}", file=sys.stderr)
            return 1
        symbols.append(
            f'  <symbol id="i-{name}" viewBox="0 0 24 24" {ATTRS}>\n'
            f"    {inner_shapes(src.read_text(encoding='utf-8'))}\n"
            f"  </symbol>"
        )
    sprite = (
        "<!-- Accountix icon sprite — Lucide 1.67.0 (ISC), self-hosted.\n"
        "     Generated by scripts/build_icon_sprite.py; see\n"
        "     static/THIRD_PARTY_NOTICES.md. Do not edit by hand. -->\n"
        '<svg xmlns="http://www.w3.org/2000/svg">\n' + "\n".join(symbols) + "\n</svg>\n"
    )
    out.write_text(sprite, encoding="utf-8")
    print(f"wrote {out} with {len(symbols)} symbols")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
