"""Guided-tour step registry (Sprint 30, ADR-057).

One entry per covered page, keyed by URL name. Each step points at
a stable ``data-tour="…"`` anchor in the page's template and carries
a gettext title + body (Persian source, English in the catalog —
the ADR-045 convention), so the tour speaks the page's language.

The payload is rendered into the page by the ``tour_data`` context
processor (``json_script``) and consumed by the self-hosted
``static/js/tour.js`` engine. Steps whose anchor is absent at
runtime — role-dependent UI, empty tables — are skipped silently
by the engine; that contract is what lets one step list serve
OWNER and VIEWER renderings of the same page.
"""

