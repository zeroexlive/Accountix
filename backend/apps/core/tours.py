def tour_payload(url_name):
    """The JSON payload for one page (or ``None`` when the page has
    no tour): steps in reading order + the engine's UI strings."""
    steps = TOURS.get(url_name or "")
    if not steps:
        return None
    return {"steps": steps, "ui": TOUR_UI}
